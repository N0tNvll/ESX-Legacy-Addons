---@alias GarageType 'public' | 'job' | 'gang' | 'impound'
---@alias vehicle_type 'car' | 'motorcycle' | 'boat' | 'aircraft' | 'bicycle' | 'truck' | 'emergency'

---@class GarageBlip
---@field sprite integer
---@field scale number
---@field color integer

---@class GaragePed
---@field model string | integer
---@field z? number
---@field heading? number
---@field snapToGround? boolean

---@class GarageAccess
---@field jobs? table<string, integer> Job name mapped to the minimum grade allowed.
---@field authorize? fun(source: integer, garage: Garage): boolean Custom server-side check, e.g. VIP or gang.

---@class Garage
---@field id string
---@field label string
---@field type GarageType
---@field entryPoint vector3
---@field storePoint? vector3
---@field spawns vector4[]
---@field blip? GarageBlip
---@field ped? GaragePed
---@field access? GarageAccess
---@field job? string Required for type='job', or use access.jobs. Matches owned_vehicles.job.
---@field minGrade? integer Minimum current job grade (default 0).
---@field shared? boolean Job fleet shared across employees (default true); false also requires owner.
---@field logo? string Image url or nui path shown in the menu header.
---@field color? string Hex accent color applied to the menu.
---@field pound? string Linked impound lot id.
---@field maxVehicles? integer

---@class Impound
---@field id string
---@field label string
---@field getOutPoint vector3
---@field spawns vector4[]
---@field blip? GarageBlip
---@field ped? GaragePed
---@field cost? integer Defaults to Config.Settings.defaultImpoundFee when omitted.

---@class GarageSettings
---@field interactionDistance number
---@field restrictToGarage boolean
---@field defaultImpoundFee integer
---@field vehicleKeys boolean
---@field storeMarkerOnlyInVehicle boolean
---@field showMarker boolean
---@field vehiclesPerPage integer
---@field maxVehiclesPerMenu integer

---@class OwnedVehicleRow
---@field owner? string Internal database owner; not returned in the vehicle list.
---@field job? string NULL/empty identifies personal vehicles.
---@field plate string
---@field vehicle string
---@field type vehicle_type
---@field stored integer
---@field parking string?
---@field pound string?
---@field custom_name string?
---@field is_favorite integer
---@field last_used integer?
---@field mileage number

---@class GarageVehicle
---@field job? string Job association; job vehicles cannot transfer ownership or grant personal keys.
---@field id string
---@field plate string
---@field model string
---@field name string
---@field type vehicle_type
---@field stored boolean
---@field garage string?
---@field impounded boolean
---@field impoundFee integer?
---@field mileage number
---@field mileageUnit 'mi'|'km'
---@field fuel number?
---@field engine number?
---@field body number?
---@field isFavorite boolean
---@field customName string?
---@field lastUsed integer?
---@field props table
