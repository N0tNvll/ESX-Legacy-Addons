for locale, values in pairs(translations) do
    if not Locales[locale] then
        Locales[locale] = {}

        for key, value in pairs(Locales.en) do
            Locales[locale][key] = value
        end
    end

    for key, value in pairs(values) do
        Locales[locale]['driving_' .. key] = value
    end
end

for _, values in pairs(Locales) do
    for key, value in pairs(translations.en) do
        if values['driving_' .. key] == nil then
            values['driving_' .. key] = value
        end
    end
end
